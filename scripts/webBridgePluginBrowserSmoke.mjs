import assert from 'node:assert/strict'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { createServer } from 'node:http'
import { build } from 'esbuild'
import { chromium } from 'playwright-core'

const directory = await mkdtemp(path.join(tmpdir(), 'web-bridge-plugin-'))
let browser, server
try {
  const bundle = path.join(directory, 'fixture.js')
  await build({ entryPoints: ['scripts/webBridgePluginBrowserFixture.tsx'], bundle: true, format: 'esm', platform: 'browser', jsx: 'automatic', outfile: bundle, logLevel: 'silent', loader: { '.wasm': 'file' },
    define: { 'process.env': JSON.stringify({ NODE_ENV: 'development' }), 'process.browser': 'true' },
    plugins: [{ name: 'controlled-diff-selection', setup(build) {
      build.onLoad({ filter: /components\/shell\/sdkBridges\.ts$/ }, () => ({ loader: 'jsx', contents: `
        import React from 'react'
        export function DiffView(props) { return <div>
          <button onClick={() => props.onSelectedLinesChange?.({ start: 1, end: 1, side: 'additions' })}>Select diff line</button>
          {(props.lineAnnotations ?? []).map((annotation, index) => <div key={index}>{props.renderAnnotation?.(annotation)}</div>)}
        </div> }
      `, resolveDir: process.cwd() }))
    } }],
  })
  const script = await readFile(bundle)
  const css = (await readFile('app/globals.css', 'utf8')).replace(/^@import[^;]+;/gm, '').replace(/@font-face\s*\{[^}]*\}/g, '')
  server = createServer((request, response) => {
    response.setHeader('Content-Type', request.url === '/fixture.js' ? 'text/javascript' : 'text/html')
    response.end(request.url === '/fixture.js' ? script : `<!doctype html><html data-theme="dark"><style>${css}</style><div id="root"></div><script type="module" src="/fixture.js"></script></html>`)
  })
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve) })
  const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ?? (existsSync(chrome) ? chrome : undefined) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(15000)
  const errors = []
  page.on('pageerror', error => { errors.push(error.message); console.error(error.stack) })
  await page.goto(`http://127.0.0.1:${server.address().port}`, { waitUntil: 'domcontentloaded' })
  const value = id => page.getByTestId(id).textContent()
  const interest = async (kind, count) => page.waitForFunction(({ kind, count }) => document.querySelector(`[data-testid="${kind}-interest"]`)?.textContent === String(count), { kind, count })
  const release = index => page.evaluate(index => window.__bridgePending[index].resolve(), index)
  const sentCount = count => page.waitForFunction(count => window.__bridgeSent.length === count, count)
  assert.equal(await value('channel-interest'), '0')
  await page.getByRole('button', { name: 'Open CLI', exact: true }).click()
  const cli = page.getByRole('region', { name: 'Live CLI bridge', exact: true })
  await cli.waitFor()
  await interest('channel', 1)
  await cli.getByRole('button', { name: /^Route composer through bridge/ }).click()
  assert.equal(await value('channel-routed'), 'true')
  await cli.getByRole('button', { name: 'Allow', exact: true }).click()
  await cli.getByText('Allowed — answered from agentViewer', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.__bridgeResponses[0]), 'permission:fixture-request:allow')
  const cliDraft = cli.getByPlaceholder('Message the live CLI session…')
  await cliDraft.fill('Scoped bridge draft')
  await cli.getByRole('button', { name: 'Connection settings', exact: true }).click()
  await cli.getByRole('textbox', { name: 'Channel server URL' }).fill('http://retained-config.test')
  await cli.getByLabel('Token (optional — AGENTVIEWER_CHANNEL_TOKEN)').fill('fixture-token')
  await page.getByRole('button', { name: 'Move placement', exact: true }).click()
  await cli.waitFor()
  await interest('channel', 1)
  assert.equal(await cliDraft.inputValue(), 'Scoped bridge draft', 'a real placement remount retains the draft')
  assert.equal(await cli.getByRole('textbox', { name: 'Channel server URL' }).inputValue(), 'http://retained-config.test')
  assert.equal(await cli.getByLabel('Token (optional — AGENTVIEWER_CHANNEL_TOKEN)').inputValue(), 'fixture-token')
  await cli.getByRole('button', { name: 'Send to live CLI session', exact: true }).click()
  await sentCount(1)
  await cli.getByRole('button', { name: 'Close', exact: true }).click()
  await cli.waitFor({ state: 'detached' })
  await interest('channel', 0)
  assert.equal(await value('channel-connected'), 'true', 'closing presentation retains a routed transport')
  await page.getByRole('button', { name: 'Open CLI', exact: true }).click()
  await cli.waitFor()
  await cliDraft.fill('Keep replacement draft')
  await release(0)
  await page.waitForTimeout(100)
  assert.equal(await cliDraft.inputValue(), 'Keep replacement draft', 'late closed-view send cannot clear its replacement')
  await cli.getByRole('button', { name: 'Send to live CLI session', exact: true }).click()
  await sentCount(2)
  await page.getByRole('button', { name: 'Disable bridges', exact: true }).click()
  await page.locator('[data-plugin-disabled="channel-bridge"]').waitFor()
  await interest('channel', 0)
  assert.equal(await value('channel-routed'), 'true')
  assert.equal(await value('channel-connected'), 'true', 'disabling presentation does not drop routing')
  await page.getByRole('button', { name: 'Open CLI', exact: true }).click()
  assert.equal(await value('handled'), 'false')
  await page.getByRole('button', { name: 'Enable bridges', exact: true }).click()
  await cli.waitFor()
  await interest('channel', 1)
  await cliDraft.fill('Keep enabled draft')
  await release(1)
  await page.waitForTimeout(100)
  assert.equal(await cliDraft.inputValue(), 'Keep enabled draft')
  assert.equal(await page.evaluate(() => window.__bridgeSent.length), 2, 're-enable never replays a send')
  await cli.getByRole('button', { name: 'Send to live CLI session', exact: true }).click()
  await sentCount(3)
  await page.getByRole('button', { name: 'Switch account', exact: true }).click()
  await cliDraft.fill('Keep work account draft')
  await release(2)
  await page.waitForTimeout(100)
  assert.equal(await cliDraft.inputValue(), 'Keep work account draft')
  assert.equal(await page.evaluate(() => window.__bridgeSent[2].account), 'personal')
  await cli.getByRole('button', { name: 'Send to live CLI session', exact: true }).click()
  await sentCount(4)
  await page.evaluate(() => window.__bridgePending[3].reject(new Error('Fixture bridge failure')))
  await cli.getByRole('alert').getByText('Fixture bridge failure', { exact: true }).waitFor()
  await cli.getByRole('button', { name: 'Dismiss error', exact: true }).click()
  assert.equal(await cli.getByRole('alert').count(), 0)
  await cli.getByRole('button', { name: 'Close', exact: true }).click()
  await interest('channel', 0)
  await page.getByRole('button', { name: 'Open IDE', exact: true }).click()
  const ide = page.getByRole('region', { name: 'IDE bridge', exact: true })
  await ide.waitFor()
  await interest('ide', 1)
  await ide.getByRole('button', { name: /^Route composer through IDE/ }).click()
  assert.equal(await value('ide-routed'), 'true')
  await page.getByRole('button', { name: 'Inject diff', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review proposed change', exact: true })
  await review.waitFor()
  await review.getByRole('button', { name: 'Select diff line', exact: true }).click()
  await review.getByRole('button', { name: 'Add comment', exact: true }).click()
  await review.getByPlaceholder('Write a comment...').fill('Keep the fixture contract')
  await review.getByRole('button', { name: 'Save comment', exact: true }).click()
  await review.getByRole('button', { name: 'Send to composer', exact: true }).click()
  const attachment = JSON.parse(await value('comment'))
  assert.equal(attachment.contextKind, 'diff')
  assert.equal(attachment.displayName, 'fixture.ts')
  assert.ok(attachment.text.includes('Keep the fixture contract'))
  await review.getByRole('button', { name: 'Accept changes', exact: true }).click()
  await review.waitFor({ state: 'detached' })
  assert.ok(await page.evaluate(() => window.__bridgeResponses.includes('diff:diff-0:accept')))
  await page.getByRole('button', { name: 'Move placement', exact: true }).click()
  await ide.waitFor()
  await interest('ide', 1)
  assert.equal(await review.count(), 0, 'a resolved diff does not auto-open again after moving')
  await ide.getByRole('button', { name: 'Close', exact: true }).click()
  await interest('ide', 0)
  assert.equal(await value('ide-connected'), 'true')
  assert.deepEqual(errors, [])
  console.log('Web bridge plugin: PASS (real plugin host, scoped placement drafts, presentation leases, routing survival, permissions, account switches, late send isolation and structured diff comments; diff renderer stubbed)')
} finally {
  await browser?.close()
  if (server) await new Promise(resolve => server.close(resolve))
  await rm(directory, { recursive: true, force: true })
}
